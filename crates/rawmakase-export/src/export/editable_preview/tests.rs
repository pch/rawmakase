//! Editable previews written here and opened again by the decoder: the pixels
//! and facts come back, highlights above white are kept, the file is an
//! ordinary linear DNG to the DNG reader, a copy this release can't read is
//! refused without a panic, and a copy renders as its original reduced to its
//! size does.
use super::*;
use crate::camera_data::{Decode, Demosaic, Metadata};
use rawmakase_decode::color_difference::{delta_e2000, lab};
use rawmakase_decode::editable_preview::record::{self as format, Record, VERSION};
use rawmakase_decode::editable_preview::{EditablePreview, open};
use rawmakase_model::model::recipe::Recipe;
use rawmakase_model::rendered::Rendered;
use rayon::prelude::*;
use std::path::PathBuf;
use std::sync::Arc;

/// A committed synthetic chart DNG (tests/corpus/README.md): a 970 × 742 RGGB
/// mosaic generated by the repository's own chart generator, so free of
/// anyone else's rights, with a gray ramp up to 3.5 EV above white that
/// clips, so highlight recovery has work to do.
fn chart(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/corpus/charts")
        .join(name)
}

/// The charts the tests use: one with an embedded camera profile, as Adobe's
/// DNG Converter writes, and one of a camera RAWmakase has a matrix for.
const CHARTS: [&str; 2] = ["synthetic-d65.dng", "fujifilm-x-t5-d65.dng"];

/// The long edge the charts' copies are reduced to, so the copy is a reduced
/// decode as a 2560-pixel copy of a camera's photo is.
const EDGE: u32 = 480;

/// The full-size decode of `path`, as Develop has it.
fn decoded(path: &Path) -> CameraImage {
    crate::photo::open(path)
        .unwrap()
        .develop(Decode::Full(Demosaic::default()), Cancel::NEVER)
        .unwrap()
}

/// A copy of the chart `name` written to a folder of its own, with what it was
/// made from.
struct Written {
    _dir: tempfile::TempDir,
    path: PathBuf,
    original: CameraImage,
}
fn written(name: &str) -> Written {
    let dir = tempfile::tempdir().unwrap();
    let original = decoded(&chart(name));
    let path = dir.path().join("1-copy.dng");
    write_at(&path, &original, None, EDGE, Cancel::NEVER).unwrap();
    Written {
        _dir: dir,
        path,
        original,
    }
}

/// The record `m` gives, its copy size aside: every fact the record keeps.
fn facts(m: &Metadata) -> Record {
    record::of(m, [1, 1], None).unwrap()
}

#[test]
fn a_copy_opens_with_its_originals_pixels_and_facts() {
    for name in CHARTS {
        let w = written(name);
        let copy = open(&w.path, Cancel::NEVER).unwrap();
        let recovered = crate::develop::quality::recovered(&w.original, Cancel::NEVER).unwrap();
        let reduced = crate::develop::preview(&recovered, EDGE);
        let image = &copy.image;
        assert_eq!((image.width, image.height), (reduced.width, reduced.height));
        assert!(image.width.max(image.height) == EDGE, "{name}: reduced");
        // Each sample within half a step of 16383 at white, times its white
        // balance, of what was written; values below 0 are written as 0.
        let wb = dng::white_balance(&w.original.metadata);
        let worst = image
            .pixels
            .iter()
            .zip(&reduced.pixels)
            .flat_map(|(a, b)| (0..3).map(move |c| (a[c] - b[c].max(0.)).abs() / wb[c]))
            .fold(0f32, f32::max);
        assert!(
            worst <= 0.5 / f32::from(dng::WHITE) + 1e-6,
            "{name}: off by {worst}"
        );
        // The facts are the original's, Auto CA as measured on it included.
        assert_eq!(
            facts(&image.metadata),
            facts(&w.original.metadata),
            "{name}"
        );
        assert!(w.original.metadata.lateral_ca.get().is_some());
        assert_eq!(
            image.metadata.lateral_ca.get(),
            w.original.metadata.lateral_ca.get()
        );
        // A reduced decode of the original's size, recovered already.
        assert!(image.fast);
        assert_eq!(
            (image.metadata.width, image.metadata.height),
            (w.original.width, w.original.height)
        );
        assert!(image.photo_scale() < 1.);
        let again = crate::develop::quality::recovered(image, Cancel::NEVER).unwrap();
        assert_eq!(again.pixels, image.pixels, "{name}: recovered twice");
        assert!(
            again.pixels.shares_buffer(&image.pixels),
            "{name}: the copy and its recovered image hold two buffers"
        );
    }
}

#[test]
fn the_synthetic_charts_embedded_profile_comes_back() {
    let w = written(CHARTS[0]);
    let copy = open(&w.path, Cancel::NEVER).unwrap();
    assert!(w.original.metadata.embedded_dcp.is_some());
    assert_eq!(
        copy.image.metadata.embedded_dcp,
        w.original.metadata.embedded_dcp
    );
}

/// A synthetic recovered image in camera space, with values up to 3.5 times
/// white, as recovery leaves the brightest highlights.
fn bright() -> CameraImage {
    let (width, height) = (64, 48);
    let metadata = Metadata {
        make: "Synthetic".into(),
        model: "Bright".into(),
        width,
        height,
        crop_width: width,
        crop_height: height,
        wb: [2.1, 1., 1.6],
        daylight_wb: [2., 1., 1.5],
        cam_xyz: [[0.7, -0.1, -0.05], [-0.4, 1.2, 0.2], [-0.05, 0.15, 0.6]],
        ..Default::default()
    };
    let pixels = (0..width * height)
        .map(|i| {
            let v = 3.5 * i as f32 / (width * height - 1) as f32;
            [v * 1.1, v, v * 0.8]
        })
        .collect();
    let image = CameraImage {
        width,
        height,
        recovered: Default::default(),
        pixels,
        metadata,
        fast: false,
        scale_factor: 1.,
        scale_clipped: 0,
        hdr: Default::default(),
    };
    let _ = image.recovered.set(Arc::new(image.clone()));
    image
}

#[test]
fn highlights_above_white_are_kept() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("bright.dng");
    let original = bright();
    write(&path, &original, None, Cancel::NEVER).unwrap();
    let copy = open(&path, Cancel::NEVER).unwrap();
    // Not reduced: the photo is smaller than the long edge.
    assert_eq!(copy.image.pixels.len(), original.pixels.len());
    let brightest = copy.image.pixels.last().unwrap();
    assert!((brightest[0] - 3.85).abs() < 1e-3, "{brightest:?}");
    let worst = copy
        .image
        .pixels
        .iter()
        .zip(&original.pixels)
        .flat_map(|(a, b)| (0..3).map(move |c| (a[c] - b[c]).abs() / b[c].max(1.)))
        .fold(0f32, f32::max);
    assert!(worst < 2.5 / f32::from(dng::WHITE), "{worst}");
}

/// To the DNG reader, without the record, the copy is an ordinary linear DNG:
/// its pixels, size, orientation, camera, white balance and color matrix are
/// what its standard tags say, and the record changes nothing it reads.
#[test]
fn a_copy_is_an_ordinary_linear_dng_to_the_dng_reader() {
    for name in CHARTS {
        let w = written(name);
        let plain = decoded(&w.path);
        let copy = open(&w.path, Cancel::NEVER).unwrap();
        assert_eq!(plain.pixels, copy.image.pixels, "{name}");
        let (m, o) = (&plain.metadata, &w.original.metadata);
        assert_eq!((m.width, m.height), (copy.image.width, copy.image.height));
        assert_eq!(m.flip, o.flip, "{name}");
        // The default crop is read from the standard tags in the copy's pixels.
        let scale = f64::from(m.width) / f64::from(o.width);
        let scaled = |v: u32| (f64::from(v) * scale).round() as i64;
        // An original without a default crop (0) is cropped to its whole frame.
        let whole = |crop: u32, size: u32| if crop > 0 { crop } else { size };
        for (read, original) in [
            (m.crop_width, whole(o.crop_width, o.width)),
            (m.crop_height, whole(o.crop_height, o.height)),
        ] {
            assert!(
                (i64::from(read) - scaled(original)).abs() <= 1,
                "{name}: crop {read} for {original} at {scale}"
            );
        }
        assert!(!plain.fast);
        let near = |a: &[f32], b: &[f32]| a.iter().zip(b).all(|(a, b)| (a - b).abs() < 1e-4);
        let normalised = |wb: [f32; 3]| wb.map(|v| v / wb[1]);
        assert!(
            near(&normalised(m.wb), &normalised(o.wb)),
            "{name}: {:?} {:?}",
            m.wb,
            o.wb
        );
        assert!(
            near(m.cam_xyz.as_flattened(), o.cam_xyz.as_flattened()),
            "{name}"
        );
        // The same DNG with another maker's private data reads the same.
        let mut bytes = std::fs::read(&w.path).unwrap();
        let at = record_at(&bytes);
        bytes[at..at + 5].copy_from_slice(b"Other");
        let other = w.path.with_file_name("other.dng");
        std::fs::write(&other, bytes).unwrap();
        assert_eq!(decoded(&other).pixels, plain.pixels);
    }
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack.windows(needle.len()).position(|w| w == needle)
}

/// Where the record starts in a copy's bytes: its magic followed by its
/// version, which the Software tag's "RAWmakase" is not.
fn record_at(bytes: &[u8]) -> usize {
    let mut start = format::MAGIC.to_vec();
    start.extend(VERSION.to_be_bytes());
    find(bytes, &start).expect("a record")
}

/// A copy this release can't read is an error for [`open`], never a panic:
/// callers count it out of date.
#[test]
fn a_copy_this_release_cant_read_is_refused() {
    let w = written(CHARTS[1]);
    let bytes = std::fs::read(&w.path).unwrap();
    let at = record_at(&bytes) + format::MAGIC.len();
    let refused = |name: &str, bytes: &[u8]| {
        let path = w.path.with_file_name(name);
        std::fs::write(&path, bytes).unwrap();
        let opened: Option<anyhow::Error> = open(&path, Cancel::NEVER).err();
        format!("{:#}", opened.unwrap_or_else(|| panic!("{name} opened")))
    };
    // A later version.
    let mut later = bytes.clone();
    later[at..at + 2].copy_from_slice(&(VERSION + 1).to_be_bytes());
    let error = refused("later.dng", &later);
    assert!(error.contains("later release"), "{error}");
    // Version 0, and a record whose JSON is damaged.
    let mut zero = bytes.clone();
    zero[at..at + 2].copy_from_slice(&0u16.to_be_bytes());
    refused("zero.dng", &zero);
    let mut damaged = bytes.clone();
    damaged[at + 2] = b'[';
    refused("damaged.dng", &damaged);
    // No record: another maker's private data, as in an ordinary DNG.
    let mut other = bytes.clone();
    other[at - format::MAGIC.len()..at - format::MAGIC.len() + 5].copy_from_slice(b"Other");
    refused("other.dng", &other);
    // Cut short anywhere: in the tiles, the directories or the record.
    for keep in [8, bytes.len() / 3, bytes.len() / 2, bytes.len() - 40] {
        refused(&format!("cut-{keep}.dng"), &bytes[..keep]);
    }
    // Not a TIFF at all, and an empty file.
    refused("text.dng", b"not a DNG");
    refused("empty.dng", b"");
    // A missing file.
    let missing = w.path.with_file_name("missing.dng");
    assert!(open(&missing, Cancel::NEVER).is_err());
}

/// The record written names each fact, and holds no identity of the
/// original: that is the catalog's row's.
#[test]
fn a_record_names_every_fact_by_its_name() {
    let w = written(CHARTS[0]);
    let record = record::of(&w.original.metadata, [3, 2], None).unwrap();
    let bytes = record::to_bytes(&record).unwrap();
    assert!(bytes.starts_with(b"RAWmakase\0\0\x01{"));
    let json: serde_json::Value = serde_json::from_slice(&bytes[12..]).unwrap();
    for name in ["width", "copy_width", "wb", "cam_xyz", "auto_ca"] {
        assert!(json.get(name).is_some(), "{name}");
    }
    assert!(json.get("original").is_none());
    assert_eq!(Record::parse(&bytes).unwrap(), record);
}

/// What version 1 can't keep is refused when building, not lost.
#[test]
fn what_a_copy_cant_keep_is_refused_when_built() {
    let dir = tempfile::tempdir().unwrap();
    let build = |im: &CameraImage| build(im, None, EDGE, Cancel::NEVER).err();
    let mut reduced = bright();
    reduced.fast = true;
    assert!(build(&reduced).is_some());
    let mut rendered = bright();
    rendered.metadata.source = rawmakase_model::camera_data::Source::Rendered;
    assert!(build(&rendered).is_some());
    let mut nan = bright();
    nan.metadata.iso = f32::NAN;
    assert!(build(&nan).is_some());
    assert!(build(&bright()).is_none());
    // Cancelled: nothing written.
    let path = dir.path().join("cancelled.dng");
    let stop = std::sync::atomic::AtomicBool::new(true);
    assert!(write(&path, &bright(), None, Cancel::new(&stop)).is_err());
    assert!(!path.exists());
}

fn srgb_lab(p: [f32; 3]) -> [f64; 3] {
    lab(p.map(|v| f64::from(rawmakase_model::color::srgb_decode(v.clamp(0., 1.)))))
}

/// Mean and 99th percentile ΔE2000 between `a` and `b`, which are the same size.
fn difference(a: &Rendered, b: &Rendered) -> [f64; 2] {
    assert_eq!((a.width, a.height), (b.width, b.height));
    let mut d: Vec<f64> = a
        .pixels
        .par_iter()
        .zip(&b.pixels)
        .map(|(a, b)| delta_e2000(srgb_lab(*a), srgb_lab(*b)))
        .collect();
    d.sort_by(f64::total_cmp);
    [
        d.iter().sum::<f64>() / d.len() as f64,
        d[(d.len() - 1) * 99 / 100],
    ]
}

/// The automated render check (docs/editable-previews.md): each chart's copy,
/// written and read back, renders as its original does at the copy's size,
/// under the default recipe and at +4 and −3 EV.
///
/// Two comparisons. Against the reduced image itself, with no file in between,
/// the file's own cost: 16-bit samples with 2 stops of headroom, and the facts
/// through the record. Against the full-size original rendered at the copy's
/// size, the copy may cost no more than the reduction alone does; on a chart of
/// sharp-edged patches that cost is large (mean about 1 to 2.2, p99 11 to 23),
/// and is any reduced copy's, not this format's.
///
/// Measured on macOS (aarch64), mean / p99 ΔE2000 of the copy's render:
///
/// | Chart | Edit | Against the reduced image | Added to the reduction's cost |
/// | --- | --- | --- | --- |
/// | synthetic-d65 | default | 0.026 / 0.085 | 0.012 / 0.007 |
/// | synthetic-d65 | +4 EV | 0.045 / 0.73 | 0.034 / 0.030 |
/// | synthetic-d65 | −3 EV | 0.008 / 0.017 | 0.003 / 0.001 |
/// | fujifilm-x-t5-d65 | default | 0.027 / 0.12 | 0.015 / 0.000 |
/// | fujifilm-x-t5-d65 | +4 EV | 0.11 / 1.31 | 0.095 / 0.049 |
/// | fujifilm-x-t5-d65 | −3 EV | 0.008 / 0.020 | 0.004 / −0.004 |
///
/// The largest gap is at +4 EV, where the chart's flat, noiseless shadows (its
/// ramp reaches 8 stops under white) show the samples' steps; a photo's noise
/// hides them, as the 13-RAW measurement found (at most 0.013 on average). The
/// bounds are about twice the largest measurement of each edit, room for
/// other platforms' float differences, not chosen to pass.
#[test]
fn a_copy_renders_as_its_original_reduced() {
    // (edit, EV, bound against the reduced image, bound added to the
    // reduction's cost), each bound a mean and a p99.
    let edits: [(&str, f32, [f64; 2], [f64; 2]); 3] = [
        ("default", 0., [0.06, 0.25], [0.04, 0.03]),
        ("+4 EV", 4., [0.25, 2.6], [0.2, 0.1]),
        ("-3 EV", -3., [0.02, 0.05], [0.01, 0.01]),
    ];
    for name in CHARTS {
        let w = written(name);
        let copy: EditablePreview = open(&w.path, Cancel::NEVER).unwrap();
        let edge = copy.image.width.max(copy.image.height);
        // The reduced image itself, as Develop would have it with no file.
        let recovered = crate::develop::quality::recovered(&w.original, Cancel::NEVER).unwrap();
        let mut reduced = crate::develop::preview(&recovered, EDGE);
        reduced.fast = true;
        let _ = reduced.recovered.set(Arc::new(reduced.clone()));
        for (label, ev, file_bound, added_bound) in edits {
            let mut recipe = Recipe::for_metadata(&w.original.metadata);
            recipe.exposure += ev;
            let r = recipe.checked().unwrap();
            let render = |im: &CameraImage| crate::develop::render(im, &r, edge, Cancel::NEVER);
            let original = render(&w.original).unwrap();
            let without_file = render(&reduced).unwrap();
            let ours = render(&copy.image).unwrap();
            let file = difference(&without_file, &ours);
            let reduction = difference(&original, &without_file);
            let total = difference(&original, &ours);
            let added = [total[0] - reduction[0], total[1] - reduction[1]];
            eprintln!(
                "{name} {label}: against the reduced image {file:.4?}, added to the reduction's cost {added:.4?}"
            );
            assert!(
                file[0] <= file_bound[0] && file[1] <= file_bound[1],
                "{name} {label}: {file:?} against the reduced image"
            );
            assert!(
                added[0] <= added_bound[0] && added[1] <= added_bound[1],
                "{name} {label}: {added:?} added to the reduction's {reduction:?}"
            );
        }
    }
}
